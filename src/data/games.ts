export function getGameById(id: string): Game | undefined {
  return games.find(g => g.id === id);
}

export function getHotGames(): Game[] {
  return games.filter(g => g.isHot);
}

export function getNewGames(): Game[] {
  return games.filter(g => g.isNew);
}

export function getWuxiaGames(): Game[] {
  return games.filter(g => 
    g.tags.some(t => t.includes('武侠') || t.includes('仙侠') || t.includes('修仙')) ||
    g.genre.includes('武侠') || g.genre.includes('仙侠')
  );
}

export function getInstantGames(): Game[] {
  return games.filter(g => g.tags.some(t => t.includes('点击即玩')));
}

export function searchGames(keyword: string): Game[] {
  const kw = keyword.toLowerCase();
  return games.filter(g => 
    g.name.toLowerCase().includes(kw) ||
    g.nameEn.toLowerCase().includes(kw) ||
    g.genre.toLowerCase().includes(kw) ||
    g.genreEn.toLowerCase().includes(kw) ||
    g.tags.some(t => t.toLowerCase().includes(kw)) ||
    g.tagsEn.some(t => t.toLowerCase().includes(kw))
  );
}
